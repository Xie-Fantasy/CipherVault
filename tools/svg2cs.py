import os
import re
import xml.etree.ElementTree as ET

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SVG_DIR = os.path.join(REPO_ROOT, 'src', 'CipherVault.UI', 'Assets', 'Icons')
OUTPUT_DIR = os.path.join(REPO_ROOT, 'src', 'CipherVault.UI', 'Helpers')
OUTPUT_FILE = os.path.join(OUTPUT_DIR, 'Icons.cs')

def to_name(filename):
    """Convert 'trash-2' to 'Trash2'"""
    parts = filename.replace('-', ' ').replace('_', ' ').split()
    name = ''.join(p.capitalize() for p in parts)
    if name and name[0].isdigit():
        name = 'I' + name
    return name

def fmt(v):
    """Format number: remove trailing .0"""
    f = float(v)
    return str(int(f)) if f == int(f) else str(f)

def circle_to_d(el):
    cx, cy, r = float(el.get('cx',0)), float(el.get('cy',0)), float(el.get('r',0))
    return f"M{fmt(cx-r)},{fmt(cy)} A{fmt(r)},{fmt(r)} 0 1 1 {fmt(cx+r)},{fmt(cy)} A{fmt(r)},{fmt(r)} 0 1 1 {fmt(cx-r)},{fmt(cy)}Z"

def ellipse_to_d(el):
    cx = float(el.get('cx',0))
    cy = float(el.get('cy',0))
    rx = float(el.get('rx',0))
    ry = float(el.get('ry',0))
    return f"M{fmt(cx-rx)},{fmt(cy)} A{fmt(rx)},{fmt(ry)} 0 1 1 {fmt(cx+rx)},{fmt(cy)} A{fmt(rx)},{fmt(ry)} 0 1 1 {fmt(cx-rx)},{fmt(cy)}Z"

def rect_to_d(el):
    w = float(el.get('width',0))
    h = float(el.get('height',0))
    x = float(el.get('x',0))
    y = float(el.get('y',0))
    rx_str = el.get('rx')
    ry_str = el.get('ry')
    # SVG spec: if only rx given, ry=rx; if only ry given, rx=ry; if neither, both=0
    if rx_str is not None and ry_str is None:
        rx = float(rx_str)
        ry = rx
    elif ry_str is not None and rx_str is None:
        ry = float(ry_str)
        rx = ry
    else:
        rx = float(rx_str) if rx_str else 0
        ry = float(ry_str) if ry_str else 0
    if rx == 0 and ry == 0:
        return f"M{fmt(x)},{fmt(y)} L{fmt(x+w)},{fmt(y)} L{fmt(x+w)},{fmt(y+h)} L{fmt(x)},{fmt(y+h)}Z"
    rx = min(rx, w/2)
    ry = min(ry, h/2)
    return (f"M{fmt(x+rx)},{fmt(y)} L{fmt(x+w-rx)},{fmt(y)} "
            f"A{fmt(rx)},{fmt(ry)} 0 0 1 {fmt(x+w)},{fmt(y+ry)} "
            f"L{fmt(x+w)},{fmt(y+h-ry)} A{fmt(rx)},{fmt(ry)} 0 0 1 {fmt(x+w-rx)},{fmt(y+h)} "
            f"L{fmt(x+rx)},{fmt(y+h)} A{fmt(rx)},{fmt(ry)} 0 0 1 {fmt(x)},{fmt(y+h-ry)} "
            f"L{fmt(x)},{fmt(y+ry)} A{fmt(rx)},{fmt(ry)} 0 0 1 {fmt(x+rx)},{fmt(y)}Z")

def line_to_d(el):
    return f"M{fmt(el.get('x1',0))},{fmt(el.get('y1',0))} L{fmt(el.get('x2',0))},{fmt(el.get('y2',0))}"

def polyline_to_d(el):
    points = el.get('points','').strip().split()
    if not points:
        return ''
    parts = [f"M{points[0].replace(',','  ')}" if i == 0 else f"L{p.replace(',','  ')}" for i, p in enumerate(points)]
    # Actually, just replace commas with spaces in the path data
    d = f"M{points[0].replace(',',',')}"
    for p in points[1:]:
        d += f" L{p.replace(',',',')}"
    return d

def polygon_to_d(el):
    d = polyline_to_d(el)
    return d + 'Z' if d else ''

def process_svg(filepath):
    tree = ET.parse(filepath)
    root = tree.getroot()
    ns = '{http://www.w3.org/2000/svg}'
    
    stroke_width = root.get('stroke-width', '2')
    stroke_cap = root.get('stroke-linecap', 'round')
    stroke_join = root.get('stroke-linejoin', 'round')
    
    cap_map = {'round': 'Round', 'square': 'Square', 'butt': 'Flat'}
    join_map = {'round': 'Round', 'miter': 'Miter', 'bevel': 'Bevel'}
    
    all_d = []
    
    for child in root:
        tag = child.tag.replace(ns, '')
        
        if tag == 'path':
            d = child.get('d', '').strip()
            if d:
                all_d.append(d)
        elif tag == 'circle':
            all_d.append(circle_to_d(child))
        elif tag == 'ellipse':
            all_d.append(ellipse_to_d(child))
        elif tag == 'rect':
            all_d.append(rect_to_d(child))
        elif tag == 'line':
            all_d.append(line_to_d(child))
        elif tag == 'polyline':
            all_d.append(polyline_to_d(child))
        elif tag == 'polygon':
            all_d.append(polygon_to_d(child))
    
    return {
        'd': ' '.join(all_d),
        'stroke_width': stroke_width,
        'stroke_cap': cap_map.get(stroke_cap, 'Round'),
        'stroke_join': join_map.get(stroke_join, 'Round'),
    }

def generate_cs(icons):
    lines = [
        '// <auto-generated>',
        '// Generated from Lucide SVG icons (https://lucide.dev) - ISC License',
        '// </auto-generated>',
        '',
        'using System.Windows.Media;',
        '',
        'namespace CipherVault.UI.Helpers;',
        '',
        '/// <summary>',
        '/// Provides icon geometry data converted from Lucide SVG icons.',
        '/// Usage in XAML: Data="{x:Static helpers:Icons.Lock}"',
        '/// </summary>',
        'public static class Icons',
        '{',
    ]
    for name, data in icons.items():
        d = data['d']
        lines.append(f'    public static readonly Geometry {name} = Geometry.Parse("{d}");')
        lines.append('')
    lines.append('}')
    return '\n'.join(lines)

def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    
    icons = {}
    for f in sorted(os.listdir(SVG_DIR)):
        if not f.endswith('.svg'):
            continue
        name = to_name(f[:-4])
        filepath = os.path.join(SVG_DIR, f)
        try:
            data = process_svg(filepath)
            if data['d']:
                icons[name] = data
                print(f"OK: {name} ({f}) - {len(data['d'])} chars")
            else:
                print(f"SKIP: {name} ({f}) - empty geometry")
        except Exception as e:
            print(f"ERR: {name} ({f}) - {e}")
    
    cs_code = generate_cs(icons)
    with open(OUTPUT_FILE, 'w', encoding='utf-8') as fout:
        fout.write(cs_code)
    
    print(f"\nGenerated {OUTPUT_FILE}")
    print(f"Total icons: {len(icons)}")

if __name__ == '__main__':
    main()
